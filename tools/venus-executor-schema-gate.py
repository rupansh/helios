import sys
from dataclasses import dataclass


REPO_DEFAULT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
GENERATOR = "tools/generate-venus-a7-schema.py"
SCHEMA = "kmd_logic/src/venus_executor/a7_schema.rs"
EXECUTOR = "kmd_logic/src/venus_executor.rs"
KMD = "kmd_render/src/ddi/native_render.rs"
MESA_DEFINES = "icd/mesa/src/virtio/venus-protocol/vn_protocol_driver_defines.h"
MESA_DRIVER = "icd/mesa/src/virtio/venus-protocol/vn_protocol_driver.h"
